// Generates src/components/map/data/world-paths.ts: land and country borders from
// Natural Earth 110m (public domain, via `world-atlas`), pre-projected with Equal Earth
// (same formula as src/components/map/projection.ts) into SVG path strings.
// Run: node scripts/gen-map-data.mjs. Dev dependencies only: nothing here ships but the output.
import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { feature, mesh } from "topojson-client"

const require = createRequire(import.meta.url)
const land = JSON.parse(readFileSync(require.resolve("world-atlas/land-110m.json"), "utf8"))
const countries = JSON.parse(
  readFileSync(require.resolve("world-atlas/countries-110m.json"), "utf8"),
)

const A1 = 1.340264,
  A2 = -0.081106,
  A3 = 0.000893,
  A4 = 0.003796,
  M = Math.sqrt(3) / 2
const X_MAX = 2.7066297319215575,
  Y_MAX = 1.3173627591574133
const W = 1000,
  S = W / (2 * X_MAX),
  H = 2 * Y_MAX * S
function project([lon, lat]) {
  const phi = (lat * Math.PI) / 180,
    lambda = (lon * Math.PI) / 180
  const t = Math.asin(M * Math.sin(phi)),
    t2 = t * t,
    t6 = t2 * t2 * t2
  const x = (lambda * Math.cos(t)) / (M * (A1 + 3 * A2 * t2 + t6 * (7 * A3 + 9 * A4 * t2)))
  const y = t * (A1 + A2 * t2 + t6 * (A3 + A4 * t2))
  return [W / 2 + x * S, H / 2 - y * S]
}
const r = (n) => Math.round(n * 10) / 10

function path(lines, close) {
  let d = ""
  for (const line of lines) {
    if (line.length < 2) continue
    // Antarctica is left out: no sensor ever sees it, and it wastes the bottom of the map.
    if (Math.max(...line.map((p) => p[1])) < -60) continue
    let prev = null
    line.forEach((p) => {
      const [x, y] = project(p).map(r)
      if (prev && prev[0] === x && prev[1] === y) return
      // A jump across the antimeridian would draw a streak across the map: start a new subpath.
      const jump = prev && Math.abs(x - prev[0]) > W / 2
      d += `${!prev || jump ? "M" : "L"}${x} ${y}`
      prev = [x, y]
    })
    if (close) d += "Z"
  }
  return d.replace(/ -/g, "-")
}

const landGeo = feature(land, land.objects.land)
const polys = (
  landGeo.type === "FeatureCollection"
    ? landGeo.features.map((f) => f.geometry)
    : [landGeo.geometry]
).flatMap((g) => (g.type === "Polygon" ? [g.coordinates] : g.coordinates))
const LAND = path(polys.flat(), true)
const borders = mesh(countries, countries.objects.countries, (a, b) => a !== b)
const BORDERS = path(
  borders.type === "MultiLineString" ? borders.coordinates : [borders.coordinates],
  false,
)

writeFileSync(
  new URL("../src/components/map/data/world-paths.ts", import.meta.url),
  `// Generated by scripts/gen-map-data.mjs from Natural Earth 110m (public domain). Do not edit.
// Equal Earth projection, ${W} x ${r(H)} map units, Antarctica left out.
export const LAND_PATH =
  "${LAND}"

export const BORDERS_PATH =
  "${BORDERS}"
`,
)
console.log("land", LAND.length, "borders", BORDERS.length)
