// Generates src/components/map/data/centroids.ts from Natural Earth 110m (public domain,
// via the `world-atlas` package). Run: node scripts/gen-centroids.mjs
// Both packages are dev dependencies only: nothing here ships to the browser.
import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { feature } from "topojson-client"
import isoCountries from "i18n-iso-countries"

const require = createRequire(import.meta.url)
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/countries-110m.json"), "utf8"))

const OUT = new URL("../src/components/map/data/", import.meta.url)
const round = (n, d = 1) => Number(n.toFixed(d))

function ringArea(ring) {
  let a = 0
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    a += ring[j][0] * ring[i][1] - ring[i][0] * ring[j][1]
  }
  return a / 2
}

function ringCentroid(ring) {
  const a = ringArea(ring)
  let x = 0
  let y = 0
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const f = ring[j][0] * ring[i][1] - ring[i][0] * ring[j][1]
    x += (ring[j][0] + ring[i][0]) * f
    y += (ring[j][1] + ring[i][1]) * f
  }
  return [x / (6 * a), y / (6 * a)]
}

// --- Country centroids: centre of the largest polygon of each country.
const centroids = {}
for (const f of feature(topo, topo.objects.countries).features) {
  const numeric = String(f.id ?? "").padStart(3, "0")
  const alpha2 = isoCountries.numericToAlpha2(numeric)
  if (!alpha2) continue
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates
  let best = null
  for (const p of polys) {
    const area = Math.abs(ringArea(p[0]))
    if (!best || area > best.area) best = { area, ring: p[0] }
  }
  let [lon, lat] = ringCentroid(best.ring)
  // Polygons that cross the antimeridian come with longitudes beyond 180.
  if (lon > 180) lon -= 360
  if (lon < -180) lon += 360
  centroids[alpha2] = [round(lat), round(lon)]
}

