"""Disk guard: system_status, maintenance_log and the size-limiting job.

Revision ID: 0005
Revises: 0004

The job itself is created by ``suckerpot_db.diskguard.apply_disk_guard`` with the ceiling from
DB_MAX_SIZE_GB; the migrate entrypoint calls it again after every upgrade.
"""

from collections.abc import Sequence

from alembic import op

from suckerpot_db.diskguard import GUARD_PROC, PROTECTED_DAYS, apply_disk_guard

revision: str = "0005"
down_revision: str | None = "0004"
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None

_PROC = f"""
CREATE OR REPLACE PROCEDURE {GUARD_PROC}(job_id integer, config jsonb)
LANGUAGE plpgsql AS $$
DECLARE
    max_bytes bigint := (config ->> 'max_bytes')::bigint;
    size bigint := pg_database_size(current_database());
    start_size bigint := size;
    dropped integer := 0;
    oldest timestamptz;
    state text := 'ok';
    status jsonb;
BEGIN
    IF size > max_bytes * 0.9 THEN
        WHILE size > max_bytes * 0.8 LOOP
            SELECT range_end INTO oldest FROM timescaledb_information.chunks
            WHERE hypertable_name = 'events'
              AND range_end < now() - make_interval(days => {PROTECTED_DAYS})
            ORDER BY range_start LIMIT 1;
            EXIT WHEN oldest IS NULL;
            -- Exactly the oldest chunk: nothing else ends before it.
            PERFORM drop_chunks('events', older_than => oldest);
            dropped := dropped + 1;
            COMMIT;
            size := pg_database_size(current_database());
        END LOOP;
        state := CASE WHEN size > max_bytes * 0.9 THEN 'critical' ELSE 'trimmed' END;
        RAISE WARNING
            'DISK GUARD: db was % MB of % MB, dropped % raw event chunk(s), now % MB (%)',
            start_size / 1048576, max_bytes / 1048576, dropped, size / 1048576, state;
        INSERT INTO maintenance_log (action, detail) VALUES (
            'disk_guard_drop_chunks',
            jsonb_build_object('state', state, 'chunks_dropped', dropped,
                               'size_before', start_size, 'size_after', size,
                               'max_bytes', max_bytes));
    END IF;
    status := jsonb_build_object(
        'state', state, 'active', state <> 'ok', 'size_bytes', size, 'max_bytes', max_bytes,
        'percent', round(size * 100.0 / max_bytes, 1));
    IF dropped > 0 THEN
        status := status || jsonb_build_object(
            'last_trim_at', now(), 'last_trim_chunks', dropped);
    END IF;
    INSERT INTO system_status AS s (key, value, updated_at)
    VALUES ('disk_guard', status, now())
    ON CONFLICT (key) DO UPDATE SET value = s.value || EXCLUDED.value, updated_at = now();
    DELETE FROM maintenance_log WHERE ts < now() - INTERVAL '90 days';
END
$$
"""


def upgrade() -> None:
    op.execute(
        """
        CREATE TABLE system_status (
            key text PRIMARY KEY,
            value jsonb NOT NULL DEFAULT '{}',
            updated_at timestamptz NOT NULL DEFAULT now()
        )
        """
    )
    op.execute(
        """
        CREATE TABLE maintenance_log (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            ts timestamptz NOT NULL DEFAULT now(),
            action text NOT NULL,
            detail jsonb NOT NULL DEFAULT '{}'
        )
        """
    )
    op.execute("CREATE INDEX ix_maintenance_log_ts ON maintenance_log (ts DESC)")
    op.execute(_PROC)
    apply_disk_guard(op.get_bind())


def downgrade() -> None:
    op.get_bind().exec_driver_sql(
        f"SELECT delete_job(job_id) FROM timescaledb_information.jobs "
        f"WHERE proc_name = '{GUARD_PROC}'"
    )
    op.execute(f"DROP PROCEDURE IF EXISTS {GUARD_PROC}(integer, jsonb)")
    op.execute("DROP TABLE IF EXISTS maintenance_log")
    op.execute("DROP TABLE IF EXISTS system_status")
