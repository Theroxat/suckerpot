def _with(io: CmdIO, flag: str) -> CmdIO:
    io.args.insert(0, flag)
    return io


def _swap_service(io: CmdIO) -> CmdIO:
    """``service NAME ACTION`` -> ``systemctl ACTION NAME``."""
    if len(io.args) >= 2:
        io.args[0], io.args[1] = io.args[1], io.args[0]
    return io
