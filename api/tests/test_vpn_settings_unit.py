PRIVATE = base64.b64encode(b"\x01" * 32).decode()
PUBLIC = base64.b64encode(b"\x02" * 32).decode()
# 9.9.9.0/24 is a global address on purpose: documentation ranges are not "global" in Python.
ENDPOINT = "9.9.9.77:51820"

PROTON = f"""\
# Generated by the provider, do not share
[Interface]
# Bouncing = 3
# NetShield = 0
PrivateKey = {PRIVATE}
Address = 198.51.100.2/32
DNS = 198.51.100.1

[Peer]
# CH#12
PublicKey = {PUBLIC}
AllowedIPs = 0.0.0.0/0, ::/0
Endpoint = {ENDPOINT}
PersistentKeepalive = 25
"""


def conf(
    *, interface: str = "", peer: str = "", private: str = PRIVATE, public: str = PUBLIC,
    address: str = "198.51.100.2/32", endpoint: str = ENDPOINT, allowed: str = "0.0.0.0/0",
) -> str:  # fmt: skip
    return (
        f"[Interface]\nPrivateKey = {private}\nAddress = {address}\n{interface}\n"
        f"[Peer]\nPublicKey = {public}\nEndpoint = {endpoint}\nAllowedIPs = {allowed}\n{peer}\n"
    )


def problems(text: str) -> tuple[str, ...]:
    result = parse_wireguard(text)
    assert result.summary is None
    return result.problems


def test_a_provider_style_file_is_accepted() -> None:
    result = parse_wireguard(PROTON)
    assert result.problems == ()
    s = result.summary
    assert s is not None
    assert (s.endpoint_ip, s.endpoint_port) == ("9.9.9.77", 51820)
    assert s.addresses == ("198.51.100.2/32",)
    assert s.public_key == PUBLIC
    assert len(s.peer_key_fingerprint) == 12
    assert PRIVATE not in repr(s)


def test_keys_are_case_insensitive_and_dns_is_ignored() -> None:
    text = PROTON.replace("PrivateKey", "privatekey").replace("[Peer]", "[peer]")
    assert parse_wireguard(text).summary is not None


def test_dual_stack_address_is_accepted() -> None:
    text = conf(address="198.51.100.2/32, fd00:1::2/128")
    s = parse_wireguard(text).summary
    assert s is not None and s.addresses == ("198.51.100.2/32", "fd00:1::2/128")


@pytest.mark.parametrize(
    "key", ["PreUp", "PostUp", "PreDown", "PostDown", "Table", "FwMark", "SaveConfig", "MTU"]
)
def test_every_dangerous_key_is_refused(key: str) -> None:
    assert problems(conf(interface=f"{key} = anything")) == ("forbidden_key",)


def test_a_preshared_key_is_refused_for_now() -> None:
    assert problems(conf(peer=f"PresharedKey = {PRIVATE}")) == ("preshared_key_refused",)


def test_an_unknown_key_is_refused() -> None:
    assert problems(conf(interface="Frobnicate = 1")) == ("unknown_key",)
    assert problems(conf(peer="ListenPort = 1")) == ("forbidden_key",)
    # a peer key in the interface section and the other way round
    assert problems(conf(interface="Endpoint = 9.9.9.77:1")) == ("unknown_key",)
    assert problems(conf(peer="Address = 198.51.100.3/32")) == ("unknown_key",)


def test_ipv6_only_address_is_refused() -> None:
    assert problems(conf(address="fd00:1::2/128")) == ("no_ipv4_address",)


@pytest.mark.parametrize("address", ["198.51.100.2", "", "x/32", "127.0.0.1/32", "0.0.0.0/0"])
def test_bad_addresses(address: str) -> None:
    assert problems(conf(address=address)) in (("bad_address",), ("missing_address",))


@pytest.mark.parametrize("endpoint", ["vpn.example.com:51820", "[2001:db8::1]:51820", "9.9.9.77"])
def test_only_an_ipv4_literal_endpoint_is_accepted(endpoint: str) -> None:
    assert problems(conf(endpoint=endpoint)) == ("endpoint_not_ip",)


@pytest.mark.parametrize(
    "endpoint",
    [
        "10.1.2.3:51820",  # gitleaks:allow
        "127.0.0.1:51820",
        "192.168.1.1:51820",  # gitleaks:allow
        "169.254.1.1:51820",
        "0.0.0.0:1",
    ],
)
def test_private_and_loopback_endpoints_are_refused(endpoint: str) -> None:
    assert problems(conf(endpoint=endpoint)) == ("endpoint_not_global",)


@pytest.mark.parametrize("port", ["0", "65536", "99999", "-1", "x", "", "0x10"])
def test_bad_ports(port: str) -> None:
    assert problems(conf(endpoint=f"9.9.9.77:{port}")) in (
        ("bad_port",),
        ("endpoint_not_ip",),
    )


def test_the_tunnel_must_be_a_full_tunnel() -> None:
    assert problems(conf(allowed="10.0.0.0/8")) == ("not_full_tunnel",)  # gitleaks:allow
    assert problems(conf(allowed="::/0")) == ("not_full_tunnel",)
    assert problems(conf(allowed="nonsense")) == ("not_full_tunnel",)
    assert parse_wireguard(conf(allowed="::/0, 0.0.0.0/0")).summary is not None


def test_two_peers_or_two_interfaces_are_refused() -> None:
    assert problems(conf() + conf()) == ("duplicate_section",)
    assert problems(conf() + f"[Peer]\nPublicKey = {PUBLIC}\n") == ("duplicate_section",)
    assert problems("[Foo]\n" + conf()) == ("unknown_section",)


def test_duplicate_keys_are_refused() -> None:
    assert problems(conf(interface=f"PrivateKey = {PRIVATE}")) == ("duplicate_key",)


def test_missing_parts() -> None:
    assert "missing_section" in problems(f"[Peer]\nPublicKey = {PUBLIC}\n")
    assert "missing_section" in problems(f"[Interface]\nPrivateKey = {PRIVATE}\n")
    assert problems("") == ("empty",)
    assert problems("# only a comment\n\n") == ("empty",)
    assert problems(f"PrivateKey = {PRIVATE}\n" + conf()) == ("syntax",)
    assert problems(conf(interface="just words")) == ("syntax",)


@pytest.mark.parametrize(
    "key", ["short", "A" * 44, "A" * 43 + "=" + "A", base64.b64encode(b"\x01" * 33).decode()]
)
def test_keys_must_be_base64_of_32_bytes(key: str) -> None:
    assert problems(conf(private=key)) == ("bad_private_key",)
    assert problems(conf(public=key)) == ("bad_public_key",)


def test_non_canonical_base64_is_refused() -> None:
    # The last character of a 32-byte key carries two spare bits that must be zero.
    assert problems(conf(private=PRIVATE[:-2] + "B=")) == ("bad_private_key",)


@pytest.mark.parametrize("bad", ["\x00", "café", "​", "\x1b[31m"])
def test_nul_and_non_ascii_bytes_are_refused(bad: str) -> None:
    assert problems(conf(interface=f"# {bad}")) == ("not_ascii",)


def test_oversize_input() -> None:
    assert problems(PROTON + "#" * MAX_CONF_BYTES) == ("too_large",)
    exactly = PROTON + "#" * (MAX_CONF_BYTES - len(PROTON) - 1) + "\n"
    assert len(exactly.encode()) == MAX_CONF_BYTES
    assert parse_wireguard(exactly).summary is not None


def test_problems_never_quote_the_input() -> None:
    secret = "SuperSecretValue123"
    for text in (conf(private=secret), conf(interface=f"PostUp = {secret}"), secret):
        assert secret not in repr(parse_wireguard(text))


