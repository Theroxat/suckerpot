@pytest.fixture
def vpn_dir(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    monkeypatch.setenv(vpn.CONFIG_DIR_ENV, str(tmp_path))
    return tmp_path


def test_write_config_is_atomic_and_world_readable(vpn_dir: Path) -> None:
    summary = parse_wireguard(PROTON).summary
    assert summary is not None
    old = os.umask(0o077)  # a restrictive umask must not leak into the file modes
    try:
        meta = vpn.write_config(summary, "admin", datetime(2026, 1, 1, tzinfo=UTC))
    finally:
        os.umask(old)
    env = vpn_dir / "wg.env"
    assert env.read_text().splitlines() == [
        f"WIREGUARD_PRIVATE_KEY={PRIVATE}",
        f"WIREGUARD_PUBLIC_KEY={PUBLIC}",
        "WIREGUARD_ADDRESSES=198.51.100.2/32",
        "WIREGUARD_ENDPOINT_IP=9.9.9.77",
        "WIREGUARD_ENDPOINT_PORT=51820",
    ]
    for name in ("wg.env", "meta.json"):
        assert stat.S_IMODE((vpn_dir / name).stat().st_mode) == 0o644
    assert sorted(p.name for p in vpn_dir.iterdir()) == ["meta.json", "wg.env"]  # no temp files
    on_disk = json.loads((vpn_dir / "meta.json").read_text())
    assert on_disk == meta
    assert set(on_disk) == {
        "uploaded_at", "uploaded_by", "endpoint_ip", "endpoint_port", "addresses",
        "peer_key_fingerprint",
    }  # fmt: skip
    assert PRIVATE not in (vpn_dir / "meta.json").read_text()
    assert vpn.read_meta() == meta


def test_remove_config_and_missing_dir(vpn_dir: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    summary = parse_wireguard(PROTON).summary
    assert summary is not None
    vpn.write_config(summary, "admin", datetime.now(UTC))
    vpn.remove_config()
    assert list(vpn_dir.iterdir()) == []
    vpn.remove_config()  # idempotent
    assert vpn.read_meta() is None
    assert vpn.config_available()
    monkeypatch.setenv(vpn.CONFIG_DIR_ENV, str(vpn_dir / "missing"))
    assert not vpn.config_available()


